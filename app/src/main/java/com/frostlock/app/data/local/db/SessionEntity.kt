package com.frostlock.app.data.local.db

import androidx.room.ColumnInfo
import androidx.room.Entity
import androidx.room.PrimaryKey

/**
 * A single focus session record. [mode] stores the enum name of the timer mode
 * (TIMER, POMODORO, STOPWATCH) as a plain string so the data layer stays independent
 * of UI code.
 */
@Entity(tableName = "focus_sessions")
data class SessionEntity(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0L,
    val mode: String,
    val plannedSeconds: Int,
    val durationSeconds: Int,
    val startedAt: Long,
    val endedAt: Long,
    val completed: Boolean,
    /** Optional subject/tag the user picked for this session ("Physics", "Work", ...). */
    @ColumnInfo(defaultValue = "''")
    val tag: String = "",
    /** A short reflection written after the session, shown in the study diary. */
    @ColumnInfo(defaultValue = "''")
    val note: String = "",
    /**
     * File name of an optional local photo in app-private storage. Empty when
     * the session has none. Only names generated by SessionPhotos are valid.
     */
    @ColumnInfo(defaultValue = "''")
    val photoPath: String = ""
) {
    companion object {
        const val MAX_NOTE_LENGTH = 280
    }
}
